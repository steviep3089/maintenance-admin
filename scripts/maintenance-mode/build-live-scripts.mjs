// Generates the LIVE Maintenance Mode SQL bundle from the scripts already verified in TESTING.
//   node scripts/maintenance-mode/build-live-scripts.mjs        (writes gitignored supabase/sql/live-generated/*.sql)
// Nothing here connects to Supabase. Each LIVE script is the verified TESTING script plus:
//   * a LIVE identity guard that aborts unless the database looks like LIVE (and not TESTING), and
//   * LIVE-specific headers (and, for the check script only, trigger handling).
// The tests regenerate in memory and fail if the committed files drift from the verified sources.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUT_DIR = "supabase/sql/live-generated";
export const LIVE_REF = "zebksrihswwwlejdiboq";
export const TESTING_REF = "etffoumsopxjptnmhvwh";

const src = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");

// The LIVE cutover migration embeds the LIVE function URL in public.notify_defect_created(); the TESTING
// equivalent embeds the TESTING URL (or does not exist). That is a project fingerprint readable from SQL.
export const GUARD = `do $live_guard$
declare
  v_def text;
begin
  select pg_get_functiondef(p.oid) into v_def
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = 'notify_defect_created'
  limit 1;
  if v_def is null or position('${LIVE_REF}' in v_def) = 0 or position('${TESTING_REF}' in v_def) > 0 then
    raise exception 'Abort: this database does not look like the LIVE project (${LIVE_REF}). Nothing was changed.';
  end if;
end
$live_guard$;
`;

function once(text, from, to, label) {
  const hits = typeof from === "string" ? text.split(from).length - 1 : (text.match(new RegExp(from.source, from.flags.replace("g", "") + "g")) || []).length;
  if (hits !== 1) throw new Error(`build-live-scripts: expected exactly one match for ${label ?? String(from)}, found ${hits}`);
  return text.replace(from, () => to);
}
const banner = (title, source, extra = "") =>
  `-- ${title}\n-- LIVE project ${LIVE_REF} ONLY. GENERATED by scripts/maintenance-mode/build-live-scripts.mjs from ${source}; do not edit by hand.\n${extra}`;

export function buildLiveScripts() {
  const out = {};
  const guarded = (file, title, source, extra = "") => {
    out[file] = banner(title, source, extra) + "\n" + GUARD + "\n" + src(source);
  };

  guarded("live-01-policy-inventory.sql", "LIVE read-only policy inventory (SELECT only).", "scripts/maintenance-mode/policy-inventory.sql",
    "-- Compare with the TESTING inventory. The header below says TESTING because this is the verified TESTING script; run it on LIVE.\n");
  guarded("live-02-baseline-fingerprint.sql", "LIVE read-only fingerprint of existing objects. Run BEFORE and AFTER every LIVE step; rows must match.", "scripts/maintenance-mode/verify-existing-unchanged.sql");

  for (const [file, source, title] of [
    ["live-03-migration-setting.sql", "supabase/migrations/20261030_maintenance_mode_setting.sql", "LIVE migration 1: Maintenance Mode tables, functions and audit triggers (OFF by default)."],
    ["live-04-migration-service-role-grants.sql", "supabase/migrations/20261030_maintenance_mode_service_role_grants.sql", "LIVE migration 2: SELECT-only service_role grants the Edge Function guard needs."],
  ]) {
    out[file] = once(banner(title, source) + "\n" + src(source), "\nbegin;\n", `\nbegin;\n${GUARD}\n`, `begin; in ${source}`);
  }

  guarded("live-05-verify-first-migration.sql", "LIVE read-only verification of migrations 1 and 2.", "scripts/maintenance-mode/verify-first-migration.sql");
  guarded("live-06-designate-super-user.sql", "LIVE Super User designation. Replace ONLY the placeholder email (an existing LIVE admin).", "scripts/maintenance-mode/designate-super-user.sql");

  let apply = src("supabase/held/20261030_maintenance_mode_enforcement_TESTING_apply.sql");
  apply = once(apply, /^-- Maintenance Mode write enforcement: APPLY\.[^\n]*\n-- on purpose:[^\n]*\n/, banner("Maintenance Mode write enforcement: APPLY.", "supabase/held/20261030_maintenance_mode_enforcement_TESTING_apply.sql",
    "-- Not in supabase/migrations on purpose: `supabase db push` must never pick it up. Run only after TESTING passed and the owner approved.\n"), "apply header");
  apply = once(apply, "-- Roll back with 20261030_maintenance_mode_enforcement_TESTING_rollback.sql.", "-- Roll back with live-09-enforcement-rollback.sql (or live-10-emergency-off.sql for an immediate restore).", "apply rollback pointer");
  apply = once(apply, "begin;\n\nset local lock_timeout = '5s';\n", `begin;\n\nset local lock_timeout = '5s';\n${GUARD}`, "apply begin");
  apply = once(apply, "scripts/maintenance-mode/verify-existing-unchanged.sql (all six rows must still match the\n-- earlier fingerprint) and scripts/maintenance-mode/check-enforcement-testing.sql.", "live-02-baseline-fingerprint.sql (all six rows must still match the\n-- earlier fingerprint) and live-08-enforcement-check.sql.", "apply next-steps");
  out["live-07-enforcement-apply.sql"] = apply;

  let check = src("scripts/maintenance-mode/check-enforcement-testing.sql");
  check = once(check, /^-- Maintenance Mode enforcement CHECK[^\n]*\n-- Run in the TESTING SQL editor[^\n]*\n/, banner("Maintenance Mode enforcement CHECK (writes + both photo buckets, ON and OFF).", "scripts/maintenance-mode/check-enforcement-testing.sql",
    "-- Run in the LIVE SQL editor as `postgres`, AFTER live-07-enforcement-apply.sql, in a quiet window.\n"), "check header");
  check = once(check, "sends nothing: it aborts if any user trigger\n-- exists on defects/defect_activity (so no notification can be queued even inside the rolled-back transaction).",
    "sends nothing: LIVE has notification triggers on\n-- defects, so it DISABLES every user trigger on defects/defect_activity for this transaction only (ALTER TABLE ... DISABLE\n-- TRIGGER is transactional) so none can fire or queue a request; the final rollback re-enables them. The disabled\n-- triggers are listed in the report (disabled_user_triggers). The table lock this takes lasts only a few seconds.", "check trigger sentence");
  check = once(check, "  v_pass text;\n", "  v_pass text;\n  v_trigs text := '';\n  r_trg record;\n", "check declarations");
  check = once(check, `  if exists (
    select 1 from pg_trigger t
    where not t.tgisinternal and t.tgenabled <> 'D'
      and t.tgrelid in ('public.defects'::regclass, 'public.defect_activity'::regclass)
  ) then
    raise exception 'Abort: a user trigger exists on defects/defect_activity; this check would fire it (even though rolled back).';
  end if;
`, `  for r_trg in
    select t.tgname, t.tgrelid::regclass::text as tbl from pg_trigger t
    where not t.tgisinternal and t.tgenabled <> 'D'
      and t.tgrelid in ('public.defects'::regclass, 'public.defect_activity'::regclass)
  loop
    execute format('alter table %s disable trigger %I', r_trg.tbl, r_trg.tgname);
    v_trigs := v_trigs || r_trg.tbl || '.' || r_trg.tgname || ' ';
  end loop;
`, "check trigger block");
  check = once(check, "Abort: TESTING needs at least one existing defect row to copy.", "Abort: LIVE needs at least one existing defect row to copy.", "check wording");
  check = once(check, "run it when TESTING is idle.", "run it when LIVE is quiet.", "check idle wording");
  check = once(check, "probe_matrix=%',", "probe_matrix=% disabled_user_triggers=%',", "check message");
  check = once(check, "v_pmatrix;", "v_pmatrix, v_trigs;", "check args");
  check = once(check, "do $check$\n", `${GUARD}\ndo $check$\n`, "check guard");
  out["live-08-enforcement-check.sql"] = check;

  // Rollback and emergency OFF deliberately carry no guard: they must never be blockable during an incident.
  let rollback = src("supabase/held/20261030_maintenance_mode_enforcement_TESTING_rollback.sql");
  rollback = once(rollback, /^-- Maintenance Mode write enforcement: EMERGENCY ROLLBACK\.[^\n]*\n/, banner("Maintenance Mode write enforcement: EMERGENCY ROLLBACK.", "supabase/held/20261030_maintenance_mode_enforcement_TESTING_rollback.sql",
    "-- No identity guard on purpose, so it can never be blocked during an incident: confirm the project in the browser first.\n"), "rollback header");
  if (rollback.split("scripts/maintenance-mode/emergency-off.sql").length - 1 !== 2) throw new Error("build-live-scripts: expected two emergency-off pointers in rollback");
  rollback = rollback.split("scripts/maintenance-mode/emergency-off.sql").join("live-10-emergency-off.sql");
  rollback = once(rollback, "Verify (read-only): scripts/maintenance-mode/verify-existing-unchanged.sql", "Verify (read-only): live-02-baseline-fingerprint.sql", "rollback verify pointer");
  out["live-09-enforcement-rollback.sql"] = rollback;

  out["live-10-emergency-off.sql"] =
    banner("LIVE EMERGENCY OFF for Maintenance Mode.", "scripts/maintenance-mode/emergency-off.sql",
      "-- No identity guard on purpose (never blockable). Confirm the project first. Restores ALL writes at once; the nine policies stay installed.\n") +
    "\n" + src("scripts/maintenance-mode/emergency-off.sql");
  // Comments inherited from the TESTING scripts that name the TESTING project would mislead an operator on LIVE.
  for (const [name, text] of Object.entries(out)) {
    out[name] = text.split("\n").map((l) => (/^\s*--/.test(l) && l.includes(TESTING_REF) ? l.split(TESTING_REF).join(LIVE_REF).replace(/\bTESTING\b/g, "LIVE") : l)).join("\n");
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(join(root, OUT_DIR), { recursive: true });
  for (const [name, text] of Object.entries(buildLiveScripts())) writeFileSync(join(root, OUT_DIR, name), text);
  console.log(`wrote ${Object.keys(buildLiveScripts()).length} files to ${OUT_DIR}`);
}
